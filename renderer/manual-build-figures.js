  /** Дуговая стрелка вращения. Углы в градусах, по часовой — от a0 к a1. */
  function spin(s, cx, cy, r, a0, a1, cls = 'fg-line') {
    const rad = (a) => (a * Math.PI) / 180;
    const x0 = cx + r * Math.cos(rad(a0)), y0 = cy + r * Math.sin(rad(a0));
    const x1 = cx + r * Math.cos(rad(a1)), y1 = cy + r * Math.sin(rad(a1));
    const cw = a1 > a0 ? 1 : 0;
    const large = Math.abs(a1 - a0) > 180 ? 1 : 0;
    path(s, `M${x0} ${y0} A${r} ${r} 0 ${large} ${cw} ${x1} ${y1}`, cls);
    // касательная в конце дуги
    const dir = cw ? 1 : -1;
    const tx = -Math.sin(rad(a1)) * dir, ty = Math.cos(rad(a1)) * dir;
    const L = 9, W = 0.45;
    const ang = Math.atan2(ty, tx);
    const p = (a) => `${x1 - L * Math.cos(a)} ${y1 - L * Math.sin(a)}`;
    add(s, E('path', { d: `M${x1} ${y1} L${p(ang - W)} L${p(ang + W)} Z`, class: 'fg-head' }));
  }

